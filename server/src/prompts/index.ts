// ---- 팀장 검토 (제출물 → 승인/반려). 구조화 출력 ----
export function reviewerBlock(args: {
  approveIf: string[];
  rejectArea: Record<string, string>;
  answerKey: unknown;
  traps: { id: string; desc: string; detect: string }[];
  attempt: number;
  rejectLimit: number;
}): string {
  return `[검토 모드]
지금은 ${args.attempt}번째 제출물을 검토합니다 (반려 상한 ${args.rejectLimit}회).
아래 정답과 기준은 당신만 압니다. 사용자에게 정답 숫자·정답 행을 절대 말하지 않습니다.

승인 조건 (전부 충족해야 승인):
${args.approveIf.map((a) => `- ${a}`).join("\n")}

반려 영역별 말투 (해당 영역이 틀렸을 때 이 수준까지만):
${Object.entries(args.rejectArea)
  .map(([k, v]) => `- ${k}: "${v}"`)
  .join("\n")}

정답 (answer_key):
${JSON.stringify(args.answerKey, null, 2)}

함정 정의 (제출물·검증 메모에서 각 함정을 잡았는지 판정):
${args.traps.map((t) => `- ${t.id}: ${t.desc} / 판정 기준: ${t.detect}`).join("\n")}

출력은 JSON 스키마대로. message 는 당신의 평소 말투로 3~5문장.
반려라도 몰아세우지 않고, 위 영역 말투 수준의 안내로 끝냅니다 (그 이상의 단서는 주지 않음).
반려 시 area 는 위 반려 영역 이름 중 하나. 승인 시 area 는 null.`;
}

// ---- 팀장 검토 멘트 (구조화 제출 시나리오). 판정은 코드가 이미 함. 정답은 주지 않음 ----
export function reviewCommentBlock(args: {
  decision: "approve" | "reject";
  wrongAreas: { area: string; line: string }[];
  taskTitle: string;
  deliverable: string;
  attempt: number;
  rejectLimit: number;
}): string {
  const verdict =
    args.decision === "approve"
      ? "판정: 승인. 제출한 숫자가 전부 맞았습니다."
      : `판정: 반려. 틀린 영역과 그 영역에서 쓰는 말투:\n${args.wrongAreas.map((w) => `- ${w.area}: "${w.line}"`).join("\n")}`;
  return `[검토 모드]
업무: ${args.taskTitle} / 요구 형식: ${args.deliverable}
지금은 ${args.attempt}번째 제출물입니다 (반려 상한 ${args.rejectLimit}회).
판정은 이미 났습니다. 당신은 판정을 바꾸지 않고, 판정을 전하는 코멘트만 씁니다.
당신도 정답 숫자는 모릅니다. 숫자를 추측하거나 "얼마 차이"를 말하지 않습니다.
반려면 틀린 영역까지만 말하고 어느 행·어느 숫자인지는 말하지 않습니다.

${verdict}

출력은 JSON 스키마대로. message 는 당신의 평소 말투로 2~4문장.
반려라도 몰아세우지 않고, 위 영역 말투 수준의 안내로 끝냅니다 (그 이상의 단서는 주지 않음).`;
}

